def glyph(char: str) -> Tuple[str, ...]:
    return _GLYPHS.get(char.upper(), _GLYPHS[" "])


def text_pixels(text: str, spacing: int = 1) -> Tuple[List[Tuple[int, int]], int, int]:
    """Return lit (x, y) pixels for `text`, plus its width and height in pixels."""
    points: List[Tuple[int, int]] = []
    cursor = 0
    for char in text:
        rows = glyph(char)
        for y, row in enumerate(rows):
            for x, bit in enumerate(row):
                if bit == "1":
                    points.append((cursor + x, y))
        cursor += GLYPH_WIDTH + spacing
    width = max(cursor - spacing, 0)
    return points, width, GLYPH_HEIGHT
